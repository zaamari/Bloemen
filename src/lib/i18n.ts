const dictionaries: Record<Locale, Dict> = { nl, en };

export function getDict(locale: Locale): Dict {
  return dictionaries[locale];
}

export function formatPrice(cents: number, locale: Locale) {
  return new Intl.NumberFormat(locale === "nl" ? "nl-NL" : "en-GB", {
    style: "currency",
    currency: "EUR",
  }).format(cents / 100);
}
